-- PairDock initial schema.
-- Pair, provision, monitor, and update Wi-Fi and Bluetooth devices.
-- Made by Sanskar.

CREATE TABLE IF NOT EXISTS Users (
  Id UUID PRIMARY KEY,
  Email VARCHAR(320) NOT NULL UNIQUE,
  DisplayName VARCHAR(160) NOT NULL,
  PasswordHash TEXT NOT NULL,
  Role VARCHAR(32) NOT NULL DEFAULT 'User',
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS Devices (
  Id UUID PRIMARY KEY,
  DeviceId VARCHAR(64) NOT NULL UNIQUE,
  SerialNumber VARCHAR(64) NOT NULL UNIQUE,
  DisplayName VARCHAR(160) NOT NULL,
  FirmwareVersion VARCHAR(64) NOT NULL DEFAULT '0.0.0',
  HardwareRevision VARCHAR(64) NOT NULL,
  ConnectionState VARCHAR(32) NOT NULL DEFAULT 'Unknown',
  LastSeenUtc TIMESTAMPTZ NULL,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS DeviceOwnership (
  Id UUID PRIMARY KEY,
  UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
  DeviceId UUID NOT NULL REFERENCES Devices(Id) ON DELETE CASCADE,
  Relationship VARCHAR(32) NOT NULL DEFAULT 'Owner',
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL,
  CONSTRAINT UX_DeviceOwnership_User_Device UNIQUE (UserId, DeviceId)
);

CREATE TABLE IF NOT EXISTS Telemetry (
  Id UUID PRIMARY KEY,
  DeviceId UUID NOT NULL REFERENCES Devices(Id) ON DELETE CASCADE,
  TimestampUtc TIMESTAMPTZ NOT NULL,
  Rssi INT NOT NULL,
  TemperatureCelsius INT NOT NULL,
  SupplyMillivolts INT NOT NULL,
  PayloadJson JSONB NOT NULL DEFAULT '{}'::jsonb,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS FirmwareVersions (
  Id UUID PRIMARY KEY,
  Version VARCHAR(64) NOT NULL,
  HardwareRevision VARCHAR(64) NOT NULL,
  PackageUrl TEXT NOT NULL,
  Sha256 CHAR(64) NOT NULL,
  Signature TEXT NOT NULL,
  IsActive BOOLEAN NOT NULL DEFAULT FALSE,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL,
  CONSTRAINT UX_FirmwareVersions_Version_Hardware UNIQUE (Version, HardwareRevision)
);

CREATE TABLE IF NOT EXISTS DeviceCommands (
  Id UUID PRIMARY KEY,
  DeviceId UUID NOT NULL REFERENCES Devices(Id) ON DELETE CASCADE,
  CommandType VARCHAR(80) NOT NULL,
  PayloadJson JSONB NOT NULL DEFAULT '{}'::jsonb,
  Status VARCHAR(32) NOT NULL DEFAULT 'Queued',
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS AuditLogs (
  Id UUID PRIMARY KEY,
  UserId UUID NULL REFERENCES Users(Id) ON DELETE SET NULL,
  Action VARCHAR(120) NOT NULL,
  Resource VARCHAR(160) NOT NULL,
  DetailsJson JSONB NOT NULL DEFAULT '{}'::jsonb,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS Notifications (
  Id UUID PRIMARY KEY,
  UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
  Title VARCHAR(160) NOT NULL,
  Message TEXT NOT NULL,
  IsRead BOOLEAN NOT NULL DEFAULT FALSE,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS ApiKeys (
  Id UUID PRIMARY KEY,
  UserId UUID NOT NULL REFERENCES Users(Id) ON DELETE CASCADE,
  Name VARCHAR(120) NOT NULL,
  KeyHash TEXT NOT NULL,
  ExpiresUtc TIMESTAMPTZ NULL,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS DeviceCertificates (
  Id UUID PRIMARY KEY,
  DeviceId UUID NOT NULL REFERENCES Devices(Id) ON DELETE CASCADE,
  Fingerprint VARCHAR(128) NOT NULL UNIQUE,
  IssuedUtc TIMESTAMPTZ NOT NULL,
  RevokedUtc TIMESTAMPTZ NULL,
  CreatedUtc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UpdatedUtc TIMESTAMPTZ NULL
);
